export function parseLocale(value: string | undefined): Locale {
  return value === "ar" ? "ar" : "en";
}

export function statusLabel(status: string): MessageKey {
  switch (status) {
    case "Contacted":
      return "statusContacted";
    case "Qualified":
      return "statusQualified";
    case "Converted":
      return "statusConverted";
    case "Lost":
      return "statusLost";
    default:
      return "statusNew";
  }
}
